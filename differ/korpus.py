# -*- coding: utf-8 -*-
"""DEAL: публичный дифференциал-корпус deal.js ↔ питон-ВМ [v0.7.0, №14, З6].

Генератор КОРПУСА — систематические сетки канон-кейсов (без случайностей:
детерминизм по построению, регресс-сетка для веб-интерпретатора). Один
файл korpus.json исполняют ОБА исполнителя, вердикты сверяет сверка.py.

Границы корпуса (хост-различия, названы честно в README):
  - полка и «время» — состояние вне корпуса (вкладка против диска);
  - глубина/топливо — хост-лимиты стека;
  - хеш от ДРОБНОГО числа — питон str() vs JS String() форматы;
  - булевы внутри склейки/хеша/максимума — str(True)/'true' форматы;
  - ключи «ключи»-словаря — не числоподобные (JS переупорядочивает);
  - стат-суд корпуса не проходит — корпус судит ИСПОЛНЕНИЕ обоих ВМ.

Прогон: python differ/korpus.py <выход.json>   (умолчание korpus.json рядом)
"""
import io
import json
import os
import sys


def pole(im):
    return {"оп": "поле", "имя": im}


def kst(z):
    return {"оп": "константа", "значение": z}


def ar(chem, l, p):
    return {"оп": "арифметика", "чем": chem, "лево": l, "право": p}


def sr(chem, l, p):
    return {"оп": "сравнение", "чем": chem, "лево": l, "право": p}


def zov(im, *a):
    return {"оп": "зов", "договор": im, "аргументы": list(a)}


def esli(uslovie, to, inache=()):
    return {"оп": "если", "условие": uslovie, "то": list(to),
            "иначе": list(inache)}


DEALS = []


def deal(imya, vhody, telo, kesi, otkazy=None, trebuet=None):
    d = {"имя": imya, "входы": [{"имя": v, "тип": "число"} for v in vhody],
         "тело": telo,
         "свидетель": [{"вход": v, "метка": m} for v, m in kesi]}
    if otkazy:
        d["отказы"] = otkazy
    if trebuet is not None:
        d["требует"] = trebuet
    DEALS.append(d)


# ── арифметика: 5 операций × сетка пар (включая знаки, дробные, нули) ──
PARY = [(7, 3), (3, 7), (-7, 3), (7, -3), (-7, -3), (2.5, 0.5), (-2.5, 0.5),
        (0.1, 0.2), (100, 7), (1, 3), (10, 4), (1e6, 1e3), (2, 0.25),
        (9, 10), (0, 5), (5, 5), (-1, 1), (2.5, 2), (7.5, 2), (0.5, 0.5),
        (0, 0), (12, -4), (-3.5, -2), (1e15, 2), (123, 1000)]
for chem, imya in (("+", "ариф-сложение"), ("-", "ариф-вычитание"),
                   ("*", "ариф-умножение"), ("/", "ариф-деление"),
                   ("%", "ариф-модуль")):
    kesi = [( {"а": a, "б": b}, "%s %s %s" % (a, chem, b)) for a, b in PARY]
    deal(imya, ["а", "б"], [{"оп": "верни", "что": ar(chem, pole("а"),
                                                      pole("б"))}], kesi)

# ── сложение типов: строки, списки, булевы, смешанное (нет_операции) ──
deal("сложение-типов", ["а", "б"],
     [{"оп": "верни", "что": ar("+", pole("а"), pole("б"))}],
     [({"а": "привет", "б": "мир"}, "строки"),
      ({"а": [1, 2], "б": [3]}, "списки"),
      ({"а": True, "б": True}, "булевы-как-целые"),
      ({"а": True, "б": 1}, "булеан-целое"),
      ({"а": 1, "б": "а"}, "число-строка: нет_операции"),
      ({"а": "а", "б": [1]}, "строка-список: нет_операции")])

# ── умножение типов: канон v0.1.3 запрещает строки и булевы нарочно ──
deal("умножение-типов", ["а", "б"],
     [{"оп": "верни", "что": ar("*", pole("а"), pole("б"))}],
     [({"а": 3, "б": 3}, "числа"),
      ({"а": "аб", "б": "в"}, "строки: типы_не_сошлись"),
      ({"а": True, "б": True}, "булевы: типы_не_сошлись"),
      ({"а": True, "б": 3}, "булеан-число: типы_не_сошлись")])

# ── порядок-сравнения: 4 оператора, булевы как целые, строки, дробные ──
for chem, imya in (("<", "срав-меньше"), (">", "срав-больше"),
                   ("<=", "срав-небольше"), (">=", "срав-неменьше")):
    kesi = [({"а": a, "б": b}, "%s %s %s" % (a, chem, b))
            for a, b in [(1, 2), (2, 2), (2.5, 2), (-1, 0), (0, -0.5),
                         (False, True), (False, False), (True, 1),
                         ("а", "б"), ("б", "а"), ("а", "а")]]
    deal(imya, ["а", "б"],
         [{"оп": "верни", "что": sr(chem, pole("а"), pole("б"))}], kesi)

# ── равно/не-равно: питон-равенство поверх типов ──
RAV = [(1, 1), (1, 1.0), (True, 1), (0, False), ("1", 1), ("аб", "аб"),
       ([1, 2], [1, 2]), ([1, 2], [2, 1]), ([1], "список-строка"),
       ({"а": 1}, {"а": 1}), ({"а": 1}, {"а": 2})]
for chem, imya in (("==", "срав-равно"), ("!=", "срав-не-равно")):
    deal(imya, ["а", "б"],
         [{"оп": "верни", "что": sr(chem, pole("а"), pole("б"))}],
         [({"а": a, "б": b}, "равенство %r %s %r" % (a, chem, b))
          for a, b in RAV])

# ── и/или/не: таблица истинности с небулевыми операндами ──
deal("логика-и", ["а", "б"],
     [{"оп": "верни", "что": {"оп": "и", "лево": pole("а"),
                              "право": pole("б")}}],
     [({"а": True, "б": True}, "ии"), ({"а": True, "б": False}, "ил"),
      ({"а": False, "б": True}, "ли"), ({"а": False, "б": False}, "лл"),
      ({"а": 1, "б": 0}, "числа"), ({"а": "х", "б": False}, "строка-ложь"),
      ({"а": 0.0, "б": True}, "нуль-истина")])
deal("логика-или", ["а", "б"],
     [{"оп": "верни", "что": {"оп": "или", "лево": pole("а"),
                              "право": pole("б")}}],
     [({"а": True, "б": False}, "ил"), ({"а": False, "б": False}, "лл"),
      ({"а": 0, "б": "х"}, "нуль-строка"), ({"а": 2, "б": 0}, "числа")])
deal("логика-не", ["а"],
     [{"оп": "верни", "что": {"оп": "не", "что": pole("а")}}],
     [({"а": True}, "истина"), ({"а": False}, "ложь"),
      ({"а": 0}, "ноль"), ({"а": "х"}, "строка")])

# ── округлено: строковый канон половины вверх (мина 1.005 прикрыта) ──
deal("округлено", ["х", "н"],
     [{"оп": "верни", "что": zov("округлено", pole("х"), pole("н"))}],
     [({"х": 1.005, "н": 2}, "1.005→1.01"), ({"х": -1.005, "н": 2}, "-1.005"),
      ({"х": 2.5, "н": 0}, "половина-вверх"), ({"х": -2.5, "н": 0}, "от-нуля"),
      ({"х": 0.125, "н": 2}, "0.13"), ({"х": 1.004, "н": 2}, "вниз"),
      ({"х": 123.456, "н": -1}, "отрицательный-разряд"),
      ({"х": 0.005, "н": 2}, "0.01"), ({"х": 1e30, "н": 0}, "громадный"),
      ({"х": 5, "н": 2}, "целое"), ({"х": 0, "н": 2}, "ноль"),
      ({"х": 1e21, "н": 0}, "экспонента-грань"),
      ({"х": 0.5, "н": 0}, "половина"), ({"х": -0.5, "н": 0}, "-половина"),
      ({"х": 987654.321, "н": 1}, "копейки")])

# ── хеш: строки, целые, экспонента-грань (дробные нет — хост-форматы) ──
deal("хеш-кейс", ["с"],
     [{"оп": "верни", "что": zov("хеш", pole("с"))}],
     [({"с": "абв"}, "строка"), ({"с": ""}, "пустая"), ({"с": "deЯ"}, "юникод"),
      ({"с": 5}, "целое"), ({"с": -5}, "отрицательное"),
      ({"с": 1e21}, "экспонента")])

# ── примитивники списков ──
deal("сумма-длина", ["сп"],
     [{"оп": "присваивание", "имя": "с", "что": zov("сумма", pole("сп"))},
      {"оп": "присваивание", "имя": "д", "что": zov("длина", pole("сп"))},
      {"оп": "верни", "что": ar("+", pole("с"), pole("д"))}],
     [({"сп": [1, 2, 3]}, "сумма+длина"), ({"сп": [1.5, 0.5]}, "дробные"),
      ({"сп": []}, "пустой")])
deal("границы-списка", ["сп"],
     [{"оп": "верни", "что": zov("максимум", pole("сп"))}],
     [({"сп": [3, 1, 2]}, "максимум"), ({"сп": [1.5, 0.5]}, "дробные"),
      ({"сп": []}, "пустой: типы_не_сошлись"),
      ({"сп": 7}, "не-список: типы_не_сошлись")])
deal("минимум-списка", ["сп"],
     [{"оп": "верни", "что": zov("минимум", pole("сп"))}],
     [({"сп": [3, 1, 2]}, "минимум"), ({"сп": [-5, -1]}, "отрицательные")])
deal("склейка", ["сп", "р"],
     [{"оп": "верни", "что": zov("склейка", pole("сп"), kst(""),
                                 pole("р"))}],
     [({"сп": [1, 2, 3], "р": "-"}, "числа"),
      ({"сп": ["а", "б"], "р": ""}, "строки"),
      ({"сп": [1.5, 2.5], "р": "|"}, "дробные"),
      ({"сп": [], "р": "x"}, "пустой"), ({"сп": [0], "р": "k"}, "ноль")])
deal("нижний-регистр", ["с"],
     [{"оп": "верни", "что": zov("нижний-регистр", pole("с"))}],
     [({"с": "ПРИВЕТ"}, "верх"), ({"с": "AbCdE"}, "смешанный"),
      ({"с": "ёЁЖ"}, "кириллица-ё")])
deal("элемент", ["сп", "и"],
     [{"оп": "верни", "что": zov("элемент", pole("сп"), pole("и"))}],
     [({"сп": [10, 20, 30], "и": 0}, "первый"),
      ({"сп": [10, 20, 30], "и": 2}, "последний"),
      ({"сп": [10, 20, 30], "и": 3}, "за-краем"),
      ({"сп": [10, 20, 30], "и": -1}, "отрицательный: за_краем"),
      ({"сп": "строка", "и": 1}, "строка"),
      ({"сп": 1, "и": 0}, "не-список: типы"),
      ({"сп": [10, 20, 30], "и": "1"}, "строковый-номер"),
      ({"сп": [10, 20, 30], "и": 1.5}, "дробный-номер")])

# ── словари: конструктор, запись, чтение-с-умолчанием, ключи ──
deal("словарь-строится", [],
     [{"оп": "присваивание", "имя": "сл", "что": zov("словарь")},
      {"оп": "присваивание", "имя": "сл",
       "что": zov("поле-записать", pole("сл"), kst("а"), kst(1))},
      {"оп": "присваивание", "имя": "сл",
       "что": zov("поле-записать", pole("сл"), kst("б"), kst(2))},
      {"оп": "верни", "что": pole("сл")}],
     [({}, "а+б")])
deal("поле-из-или", ["сл", "ключ"],
     [{"оп": "верни", "что": zov("поле-из-или", pole("сл"), pole("ключ"),
                                 kst(99))}],
     [({"сл": {"а": 1}, "ключ": "а"}, "есть"),
      ({"сл": {"а": 1}, "ключ": "б"}, "нет: умолчание"),
      ({"сл": 7, "ключ": "х"}, "не-словарь: умолчание")])
deal("ключи", ["сл"],
     [{"оп": "верни", "что": zov("ключи", pole("сл"))}],
     [({"сл": {"а": 1, "б": 2}}, "два"), ({"сл": {}}, "пустой")])
deal("тип-из", ["х"],
     [{"оп": "верни", "что": zov("тип-из", pole("х"))}],
     [({"х": 5}, "число"), ({"х": 5.5}, "дробное"), ({"х": "с"}, "строка"),
      ({"х": [1]}, "список"), ({"х": {"а": 1}}, "словарь"),
      ({"х": True}, "статус")])

# ── тела: если обе ветви, вложенные, без иначе с отказом нет_имени ──
deal("ветвь", ["х"],
     [esli(sr(">", pole("х"), kst(0)), [{"оп": "верни", "что": kst(1)}],
           [{"оп": "верни", "что": kst(-1)}])],
     [({"х": 5}, "то"), ({"х": -5}, "иначе"), ({"х": 0}, "грань-иначе")])
deal("ветвь-вложенная", ["х"],
     [esli(sr(">", pole("х"), kst(10)),
           [esli(sr(">", pole("х"), kst(100)),
                 [{"оп": "верни", "что": kst(2)}],
                 [{"оп": "верни", "что": kst(1)}])],
           [{"оп": "верни", "что": kst(0)}])],
     [({"х": 200}, "глубоко"), ({"х": 50}, "мелко"), ({"х": 5}, "мимо")])
deal("ветвь-без-иначе", ["х"],
     [esli(sr(">", pole("х"), kst(0)),
           [{"оп": "присваивание", "имя": "у", "что": pole("х")}]),
      {"оп": "верни", "что": pole("у")}],
     [({"х": 5}, "ветвь-взята"),
      ({"х": -5}, "мимо: нет_имени")])

# ── циклы: сумма, факториал, верни-из-цикла ──
deal("сумма-до", ["н"],
     [{"оп": "присваивание", "имя": "с", "что": kst(0)},
      {"оп": "для-каждого-до", "переменная": "и", "до": pole("н"),
       "тело": [{"оп": "присваивание", "имя": "с",
                 "что": ar("+", pole("с"), pole("и"))}]},
      {"оп": "верни", "что": pole("с")}],
     [({"н": 0}, "ноль-витков"), ({"н": 1}, "один"), ({"н": 5}, "пять"),
      ({"н": 10}, "десять")])
deal("факториал-циклом", ["н"],
     [{"оп": "присваивание", "имя": "р", "что": kst(1)},
      {"оп": "для-каждого-до", "переменная": "и", "до": pole("н"),
       "тело": [{"оп": "присваивание", "имя": "р",
                 "что": ar("*", pole("р"), ar("+", pole("и"), kst(1)))}]},
      {"оп": "верни", "что": pole("р")}],
     [({"н": 0}, "ноль"), ({"н": 1}, "один"), ({"н": 5}, "пять"),
      ({"н": 7}, "семь")])
deal("верни-из-цикла", ["н"],
     [{"оп": "для-каждого-до", "переменная": "и",
       "до": zov("длина", kst("абвгдежзи")),
       "тело": [esli(sr(">", ar("*", pole("и"), pole("и")), pole("н")),
                     [{"оп": "верни", "что": pole("и")}])]},
      {"оп": "верни", "что": kst(-1)}],
     [({"н": 0}, "первый-же"), ({"н": 4}, "три"), ({"н": 25}, "шесть"),
      ({"н": -1}, "отрицательный")])

# ── присоединить: накопление и реверс ──
deal("накопление", ["н"],
     [{"оп": "присваивание", "имя": "р", "что": zov("список")},
      {"оп": "для-каждого-до", "переменная": "и", "до": pole("н"),
       "тело": [{"оп": "присоединить", "имя": "р",
                 "что": ar("*", pole("и"), pole("и"))}]},
      {"оп": "верни", "что": pole("р")}],
     [({"н": 0}, "пусто"), ({"н": 3}, "три"), ({"н": 5}, "пять")])
deal("реверс", ["сп"],
     [{"оп": "присваивание", "имя": "р", "что": zov("список")},
      {"оп": "для-каждого-до", "переменная": "и",
       "до": zov("длина", pole("сп")),
       "тело": [{"оп": "присоединить", "имя": "р",
                 "что": zov("элемент", pole("сп"),
                            ar("-", zov("длина", pole("сп")),
                               ar("+", pole("и"), kst(1))))}]},
      {"оп": "верни", "что": pole("р")}],
     [({"сп": [1, 2, 3]}, "три"), ({"сп": []}, "пусто"),
      ({"сп": ["а"]}, "один")])

# ── зовы: цепочка, рекурсия, отказ-сквозь-зов, требует, арность ──
deal("тройнуть", ["х"],
     [{"оп": "верни", "что": ar("*", pole("х"), kst(3))}],
     [({"х": 5}, "пять")])
deal("удвоить", ["х"],
     [{"оп": "верни", "что": ar("*", pole("х"), kst(2))}],
     [({"х": 5}, "пять")])
deal("цепь", ["х"],
     [{"оп": "верни", "что": zov("удвоить", zov("тройнуть", pole("х")))}],
     [({"х": 5}, "тридцать"), ({"х": 0}, "ноль")])
deal("факт-рекурсия", ["х"],
     [esli(sr("<=", pole("х"), kst(1)), [{"оп": "верни", "что": kst(1)}],
           [{"оп": "верни", "что": ar("*", pole("х"),
                                      zov("факт-рекурсия",
                                          ar("-", pole("х"), kst(1))))}])],
     [({"х": 0}, "ноль"), ({"х": 5}, "пять")])
deal("делитель", ["а", "б"],
     [{"оп": "верни", "что": ar("/", pole("а"), pole("б"))}],
     [({"а": 10, "б": 2}, "пять"), ({"а": 5, "б": 0}, "ноль: отказ")])
deal("зов-отказ-сквозь", ["а", "б"],
     [{"оп": "верни", "что": zov("делитель", pole("а"), pole("б"))}],
     [({"а": 10, "б": 2}, "живой"), ({"а": 5, "б": 0}, "отказ-едет")])
deal("зов-арность", ["а"],
     [{"оп": "верни", "что": zov("делитель", pole("а"))}],
     [({"а": 1}, "не-хватает: нарушен_договор")])
deal("ограниченная", ["х"],
     [{"оп": "верни", "что": ar("*", pole("х"), kst(2))}],
     [({"х": 5}, "пять"),
      ({"х": -1}, "требует свидетелем не судится: просто -2")],
     trebuet=sr(">=", pole("х"), kst(0)))
deal("зов-требует", ["х"],
     [{"оп": "верни", "что": zov("ограниченная", pole("х"))}],
     [({"х": 5}, "живой"), ({"х": -1}, "требует-режет")])

# ── стой с названным отказом ──
deal("стой-деловое", ["х"],
     [esli(sr("<", pole("х"), kst(0)),
           [{"оп": "стой", "отказ": "деловое",
             "причина": "отрицательное не берём"}]),
      {"оп": "верни", "что": pole("х")}],
     [({"х": 5}, "живой"), ({"х": -3}, "отказ"), ({"х": 0}, "грань")],
     otkazy=["деловое"])


def sobrat_korpus():
    vsego = sum(len(d["свидетель"]) for d in DEALS)
    return {"корпус": "differ-v1", "сделок": len(DEALS), "кейсов": vsego,
            "граница": "полка/время/глубина/топливо/хеш-дробного/булевы-в-"
                       "строках/числоподобные-ключи — вне корпуса (хосты)",
            "сделки": DEALS}


def main():
    vyhod = sys.argv[1] if len(sys.argv) > 1 else os.path.join(
        os.path.dirname(os.path.abspath(__file__)), "korpus.json")
    korpus = sobrat_korpus()
    with io.open(vyhod, "w", encoding="utf-8", newline="\n") as fh:
        json.dump(korpus, fh, ensure_ascii=False, sort_keys=True, indent=1)
    print("korpus: %d сделок, %d кейсов → %s" % (korpus["сделок"],
                                                 korpus["кейсов"], vyhod))


if __name__ == "__main__":
    main()
