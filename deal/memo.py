# -*- coding: utf-8 -*-
"""DEAL: мемоизация ЧИСТЫХ сделок — топливо-нейтральная [v0.10.0, раунд 11
QWEN; дизайн его, реализация наша, гейт — дифференциал-корпус].

Доказанная чистота (kesh.chistaya — транзитивное замыкание зова без полки
и «времени») открывает законную оптимизацию, недоступную Rust: вердикт
чистой сделки = f(AST, аргументы) → кэш по содержанию аргументов.

Топливо-нейтральность — КРАЙ КАНОНА: на попадании списывается ПОЛНАЯ
стоимость поддерева в шагах (запомнена на промахе) — суммарный счёт
топлива и вердикт «топливо» не меняются от того, было пересчитывание или
попадание. Отказы чистой сделки тоже кэшируются (кроме хост-контрактов
«топливо»/«глубина» — те зависят от контекста вызова и не мемоизируются).

Границы названы:
  - чистота кэшируется по (id сделки, id словаря сделок) — объекты живут
    весь расчёт (держатель — файл/корпус), id-переиспользование между
    расчётами исключено пересозданием _МЕМО на процесс;
  - ключ аргументов: хешируемые — кортежем, прочие — канон-JSON
    (числово-равные 1 и 1.0 дают разные ключи — в сторону лишнего
    пересчёта, не неверного ответа);
  - рубильник: РЕЖИМ["мемо"] (умолчание вкл) / DEAL_MEMO=0.
"""
import json
import os

# кэши живут на процесс (модуль-глобалы) — между расчётами не перетекают
_МЕМО = {}
_ЧИСТ = {}
_dkesh = None


def sverni(sdelka, argy, sdelki, basa):
    """Обёртка зова: попадание — вердикт из кэша + списание полной
    стоимости; промах — расчёт базовым зовом и запоминание. basa —
    прежняя функция зова (глубина, требует, тело)."""
    global _dkesh
    import deal.vm as dvm

    vhody = sdelka.get("входы", [])
    memo = None
    if dvm.РЕЖИМ.get("мемо"):
        if _dkesh is None:
            from deal import kesh as _dkesh_mod
            _dkesh = _dkesh_mod
        ck = (id(sdelka), id(sdelki))
        ch = _ЧИСТ.get(ck)
        if ch is None:
            ch = _dkesh.chistaya(sdelka, sdelki)
            _ЧИСТ[ck] = ch
        if ch:
            try:
                ak = (1, tuple(argy))
                hash(ak)
            except TypeError:
                ak = (2, json.dumps(argy, ensure_ascii=False, sort_keys=True,
                                    separators=(",", ":")))
            memo = (id(sdelka), ak)
            zap = _МЕМО.get(memo)
            if zap is not None:
                dvm._топливо += zap[-1]
                if dvm._топливо > dvm._ТОПЛИВО_ЛИМИТ:
                    raise dvm.DealOtkaz(
                        "топливо",
                        "расчёт израсходовал %d шагов тела — проверь границы "
                        "циклов" % dvm._ТОПЛИВО_ЛИМИТ)
                if zap[0] == "отказ":
                    raise dvm.DealOtkaz(zap[1], zap[2])
                return zap[1]
    do = dvm._топливо
    try:
        rez = basa(sdelka, argy, sdelki)
    except dvm.DealOtkaz as otk:
        if memo is not None and otk.imya not in ("топливо", "глубина"):
            _МЕМО[memo] = ("отказ", otk.imya, str(otk), dvm._топливо - do)
        raise
    if memo is not None:
        _МЕМО[memo] = ("знач", rez, dvm._топливо - do)
    return rez


def sbros():
    """Сброс кэшей (для проб: границы процессов и так изолируют)."""
    _МЕМО.clear()
    _ЧИСТ.clear()
